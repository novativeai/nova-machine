// Get videos by aspect ratio
export const getLandscapeVideos = () => VIDEO_CATALOG.filter((v) => v.aspect === 'landscape');
export const getPortraitVideos = () => VIDEO_CATALOG.filter((v) => v.aspect === 'portrait');
export const getSquareVideos = () => VIDEO_CATALOG.filter((v) => v.aspect === 'square');

// Get videos by category
export const getVideosByCategory = (category: string) =>
  category === 'All' ? VIDEO_CATALOG : VIDEO_CATALOG.filter((v) => v.category === category);

// Get videos by tag
export const getVideosByTag = (tag: string) => VIDEO_CATALOG.filter((v) => v.tags.includes(tag));

// Get random videos
export const getRandomVideos = (count: number) => {
  const shuffled = [...VIDEO_CATALOG].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count);
};
